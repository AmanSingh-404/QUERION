import json
from pathlib import Path

BENCH = Path(__file__).resolve().parents[1] / "benchmarks"
HEADER = [
    "Run",
    "Questions",
    "Clients",
    "Samples",
    "int8",
    "Accuracy (matches)",
    "Questions/s",
    "Latency p50 (s)",
    "Latency p95 (s)",
    "Prefix hit rate",
    "Peak GPU (GB)",
]


def row_text(name, s):
    gpu = f"{s['peak_gpu_gb']:.2f}" if "peak_gpu_gb" in s else "-"
    cells = [
        name,
        str(s["items"]),
        str(s["clients"]),
        str(s["samples"]),
        "yes" if s.get("int8") else "no",
        f"{s['exec_accuracy']:.1%} ({s['matches']})",
        f"{s['questions_per_second']:.2f}",
        f"{s['latency_p50']:.2f}",
        f"{s['latency_p95']:.2f}",
        f"{s['prefix_hit_rate']:.0%}",
        gpu,
    ]
    return "| " + " | ".join(cells) + " |"


def main():
    runs = []
    for path in BENCH.glob("pipeline_*.json"):
        runs.append((path.stem.removeprefix("pipeline_"), json.loads(path.read_text("utf-8"))))
    runs.sort(key=lambda r: (-r[1]["items"], r[1]["samples"], r[1]["clients"]))
    lines = [
        "# Full pipeline through the serving engine",
        "",
        "Generated by `scripts/collect_pipeline_table.py` from `benchmarks/pipeline_*.json`.",
        "Spider dev questions answered with the schema constraint, sampled candidates and the",
        "execution vote, decoded by the engine (prefix cache on). Latency is per question.",
        "",
        "| " + " | ".join(HEADER) + " |",
        "|" + "---|" * len(HEADER),
    ]
    lines += [row_text(name, summary) for name, summary in runs]
    text = "\n".join(lines) + "\n"
    (BENCH / "pipeline_table.md").write_text(text, encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
