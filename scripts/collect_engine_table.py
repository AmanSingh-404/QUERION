import json
from pathlib import Path

BENCH = Path(__file__).resolve().parents[1] / "benchmarks"

# (file, engine A, engine B, feature name, workload)
SPECS = [
    ("engine_compare.json", "baseline", "batched", "Continuous batching", "GPU, 32 spread"),
    (
        "compare_batched_vs_paged.json",
        "batched",
        "paged",
        "Paged KV (1024 blocks)",
        "GPU, 32 spread",
    ),
    (
        "compare_batched_vs_paged_512.json",
        "batched",
        "paged",
        "Paged KV (512 blocks)",
        "GPU, 32 spread",
    ),
    ("compare_paged_vs_prefix_spread.json", "paged", "prefix", "Prefix cache", "GPU, 32 spread"),
    (
        "compare_paged_vs_prefix_clustered.json",
        "paged",
        "prefix",
        "Prefix cache",
        "GPU, 64 clustered",
    ),
    (
        "compare_paged_vs_prefix_clustered_cpu.json",
        "paged",
        "prefix",
        "Prefix cache",
        "CPU, 16 clustered",
    ),
]
HEADER = [
    "Feature",
    "Compared",
    "Workload",
    "Clients",
    "tokens/s",
    "Throughput ratio (range)",
    "First-token speedup",
    "Latency p50 (s)",
    "KV reserved (GB)",
    "KV peak used (GB)",
    "Prefix hit rate",
]


def pair(ra, rb, key, fmt):
    va, vb = ra.get(key), rb.get(key)
    if va is None or vb is None:
        return "-"
    return f"{va:{fmt}} -> {vb:{fmt}}"


def row_text(feature, workload, a, b, row):
    ra, rb = row[a], row[b]
    spread = row["speedup_all"]
    ratio = f"{row['speedup_median']:.2f}x ({min(spread):.2f}-{max(spread):.2f})"
    ttft = row.get("ttft_speedup_median")
    first = f"{ttft:.2f}x" if ttft is not None else "-"
    hit = rb.get("prefix_hit_rate")
    cells = [
        feature,
        f"{a} -> {b}",
        workload,
        str(row["clients"]),
        pair(ra, rb, "tokens_per_second", ".0f"),
        ratio,
        first,
        pair(ra, rb, "latency_p50", ".2f"),
        pair(ra, rb, "kv_reserved_gb", ".2f"),
        pair(ra, rb, "kv_peak_used_gb", ".3f"),
        f"{hit:.0%}" if hit is not None else "-",
    ]
    return "| " + " | ".join(cells) + " |"


def main():
    lines = [
        "# Engine benchmark table",
        "",
        "Generated by `scripts/collect_engine_table.py` from the interleaved A/B runs in this",
        "folder. Each row compares two engines on the same machine, back to back, alternating",
        "which goes first. The throughput ratio is the median of the per-repeat ratios, with the",
        "range over repeats in brackets. `->` reads as engine A to engine B. A `-` means the run",
        "did not record that value. Workloads: `spread` is questions spread over the dev set,",
        "`clustered` is the first dev questions in order (consecutive ones share a database).",
        "",
        "| " + " | ".join(HEADER) + " |",
        "|" + "---|" * len(HEADER),
    ]
    for name, a, b, feature, workload in SPECS:
        path = BENCH / name
        if not path.exists():
            print("missing:", path)
            continue
        data = json.loads(path.read_text(encoding="utf-8"))
        for row in data["rows"]:
            lines.append(row_text(feature, workload, a, b, row))
    text = "\n".join(lines) + "\n"
    (BENCH / "engine_table.md").write_text(text, encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
